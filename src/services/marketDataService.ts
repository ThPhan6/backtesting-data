// A simple cache to avoid parsing the large CSV string every time.
let parsedBtcData: PriceDataPoint[] | null = null;

const getBtcData = (): PriceDataPoint[] => {
    if (parsedBtcData) {
        return parsedBtcData;
    }

    const lines = BTC_USD_DATA_CSV.trim().split('\n');
    const data = lines
        .slice(1) // Skip header
        .map(line => {
            const parts = line.split(',');
            // Date is "Month Day, Year", so it takes up parts[0] and parts[1].
            // We need at least 6 parts for Date(2), Open, High, Low, Close.
            if (parts.length < 6) return null;
            const dateStr = `${parts[0]},${parts[1]}`; // e.g., "Sep 3, 2025"
            const closePrice = parseFloat(parts[5]); // Close price is at index 5
            return {
                date: new Date(dateStr),
                price: closePrice,
            };
        })
        .filter((p): p is PriceDataPoint => p !== null && !isNaN(p.date.getTime()) && !isNaN(p.price));
    
    // The data is newest-first, so we reverse it to be chronological.
    parsedBtcData = data.reverse();
    return parsedBtcData;
};

export const fetchMarketData = async (
    symbol: string,
    startDate: string,
    endDate: string
): Promise<PriceDataPoint[]> => {
    console.log(`Fetching MOCK market data for ${symbol} from ${startDate} to ${endDate}...`);
    
    if (symbol.toUpperCase() !== 'BTC-USD') {
        // For now, we only have BTC-USD data.
        throw new Error(`Market data for symbol ${symbol} is not available in this mock service.`);
    }

    const allBtcData = getBtcData();
    const start = new Date(startDate);
    const end = new Date(endDate);
    
    const filteredData = allBtcData.filter(d => d.date >= start && d.date <= end);
    
    return Promise.resolve(filteredData);
};

